<?php

declare(strict_types=1);

namespace Yuuues\YuuuUi\Tests\Support;

use Yuuues\YuuuUi\YuuuUiBundle;

/**
 * `public/css/tokens.css` is GENERATED from section 1 of `yuuu-base.css`:
 * the base stays the one source of truth (the Twig apps keep linking one
 * file, with the same fingerprint), and `tokens.css` is that section
 * alone, for the JavaScript apps that bring their own rules.
 *
 * `bin/build-tokens` writes it; TokensStylesheetTest fails while the
 * committed file differs from what this class renders. The file is
 * committed, never built on install: npm installs the package from a git
 * tag, and with `ignore-scripts` no install script would ever run.
 */
final class TokensStylesheet
{
    private const string HEADER = <<<'CSS'
        /*
         * yuuu-ui: the design tokens of the yuuu suite, alone.
         *
         * GENERATED from section 1 of public/css/yuuu-base.css by
         * bin/build-tokens. Do not edit this file: edit yuuu-base.css and run
         * the script. The suite fails while the two differ.
         *
         * For apps that bring their own rules (a JavaScript app, a single-file
         * page): the palette with its dark mode, the type, the spacing and the
         * shapes, without the base classes. yuuu-base.css already contains all
         * of this: use one file or the other.
         */


        CSS;

    public static function path(): string
    {
        return \dirname(YuuuUiBundle::stylesheetPath()).'/tokens.css';
    }

    /** What `tokens.css` must contain for the given base stylesheet. */
    public static function render(string $base): string
    {
        $start = self::sectionStart($base, '1. Tokens');
        $end = self::sectionStart($base, '2. Base elements');

        if ($end <= $start) {
            throw new \RuntimeException('yuuu-base.css: section 2 comes before section 1.');
        }

        return self::HEADER.rtrim(substr($base, $start, $end - $start))."\n";
    }

    /** Offset of the `/* ----` banner whose title line is ` * $title`. */
    private static function sectionStart(string $css, string $title): int
    {
        $pattern = '#^/\* -+\n \* '.preg_quote($title, '#').'\n#m';

        if (1 !== preg_match($pattern, $css, $match, \PREG_OFFSET_CAPTURE)) {
            throw new \RuntimeException(\sprintf('yuuu-base.css: cannot find the "%s" banner.', $title));
        }

        return $match[0][1];
    }
}
